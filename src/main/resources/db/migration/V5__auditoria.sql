ALTER TABLE categorias ADD (creado_por VARCHAR2(100) DEFAULT 'sistema' NOT NULL, modificado_por VARCHAR2(100));
ALTER TABLE productos ADD (creado_por VARCHAR2(100) DEFAULT 'sistema' NOT NULL, modificado_por VARCHAR2(100));
ALTER TABLE clientes ADD (creado_por VARCHAR2(100) DEFAULT 'sistema' NOT NULL, modificado_por VARCHAR2(100));
ALTER TABLE ventas ADD (creado_por VARCHAR2(100) DEFAULT 'sistema' NOT NULL);
CREATE TABLE auditoria_eventos (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha TIMESTAMP NOT NULL,
 usuario VARCHAR2(100) NOT NULL,
 accion VARCHAR2(60) NOT NULL,
 entidad VARCHAR2(60) NOT NULL,
 entidad_id NUMBER(19),
 detalle VARCHAR2(500),
 request_id VARCHAR2(36)
);
CREATE INDEX ix_auditoria_fecha ON auditoria_eventos(fecha);
CREATE INDEX ix_auditoria_usuario_fecha ON auditoria_eventos(usuario,fecha);
CREATE INDEX ix_productos_nombre ON productos(nombre);
-- La aplicación expone únicamente consulta y escritura por inserción.
CREATE OR REPLACE TRIGGER tr_auditoria_inmutable
BEFORE UPDATE OR DELETE ON auditoria_eventos
