CREATE TABLE empleados (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR2(8 CHAR) NOT NULL,
    nombres VARCHAR2(100 CHAR) NOT NULL,
    apellidos VARCHAR2(100 CHAR) NOT NULL,
    cargo VARCHAR2(100 CHAR) NOT NULL,
    email VARCHAR2(150 CHAR) NOT NULL,
    telefono VARCHAR2(20 CHAR),
    estado NUMBER(1) DEFAULT 1 NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP,
    CONSTRAINT uk_empleados_dni UNIQUE (dni),
    CONSTRAINT uk_empleados_email UNIQUE (email)
);

CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(30 CHAR) NOT NULL,
    descripcion VARCHAR2(200 CHAR),
    CONSTRAINT uk_roles_nombre UNIQUE (nombre)
);

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50 CHAR) NOT NULL,
    password VARCHAR2(60 CHAR) NOT NULL,
    estado NUMBER(1) DEFAULT 1 NOT NULL,
    empleado_id NUMBER NOT NULL,
    CONSTRAINT uk_usuarios_empleado UNIQUE (empleado_id),
    CONSTRAINT fk_usuarios_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);

CREATE UNIQUE INDEX ux_usuarios_username_upper ON usuarios (UPPER(username));

CREATE TABLE usuario_roles (
    usuario_id NUMBER NOT NULL,
    rol_id NUMBER NOT NULL,
    CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuario_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_roles_rol FOREIGN KEY (rol_id) REFERENCES roles (id) ON DELETE CASCADE
);

